#!/usr/bin/env python3
"""Build the second-year CSE student directory for AuPro from the xlsx.

Usage:
    python3 scripts/build-student-directory.py <path-to-xlsx>

Reads the sheet `CSE-1-2-3-4-5-6-7-8` (header: s.no, sec, name,
registration number) and writes two files from the same data:

  * apps/web/app/lib/cse-students.ts   — the directory module imported
    by the OTP routes and the client signup form.
  * apps/web/app/lib/cse-students.json — the same data as JSON, read by
    app/api/auth/account-registry.ts with fs (that registry cannot import
    the .ts module: an extensionless import cannot resolve under
    node --test, and a .ts extension breaks tsc with TS5097).

Name spellings are kept verbatim from the sheet — never "corrected".
Email for a student is <registration number>@andhrauniversity.edu.in.
Every student is 2nd Year, department Computer Science & Engineering.
"""
import json
import sys
from pathlib import Path

import openpyxl

REPO_ROOT = Path(__file__).resolve().parent.parent
OUT_TS = REPO_ROOT / "apps" / "web" / "app" / "lib" / "cse-students.ts"
OUT_JSON = REPO_ROOT / "apps" / "web" / "app" / "lib" / "cse-students.json"
SHEET = "CSE-1-2-3-4-5-6-7-8"
DEPARTMENT = "Computer Science & Engineering"
YEAR = "2nd Year"


def main() -> None:
    if len(sys.argv) < 2:
        print("usage: build-student-directory.py <path-to-xlsx>", file=sys.stderr)
        sys.exit(1)
    xlsx_path = Path(sys.argv[1])
    wb = openpyxl.load_workbook(xlsx_path, read_only=True)
    ws = wb[SHEET]
    rows = list(ws.iter_rows(values_only=True))
    header = rows[0]
    assert tuple(header) == ("s.no", "sec", "name", "registration number"), header

    students = {}
    for row in rows[1:]:
        _sno, section, name, reg = row
        reg = str(reg).strip()
        assert reg.isdigit() and len(reg) == 12, reg
        assert name and str(name).strip(), reg
        assert reg not in students, f"duplicate registration number {reg}"
        students[reg] = {"name": str(name), "section": str(section).strip()}

    # --- cse-students.ts -------------------------------------------------
    entries = ",\n".join(
        f"  {json.dumps(reg)}: {{ name: {json.dumps(v['name'], ensure_ascii=False)}, section: {json.dumps(v['section'])} }}"
        for reg, v in sorted(students.items())
    )
    ts = f"""/**
 * Second-year CSE student directory for AuPro.
 *
 * GENERATED by scripts/build-student-directory.py from the CSE second-year
 * list — do not edit by hand. Re-run the generator to refresh it.
 * Name spellings are verbatim from the sheet.
 *
 * Login rule: a student's email local part IS their roll number
 * (<registration number>@andhrauniversity.edu.in). Look the roll number
 * up here and the name, roll number, year and section attach
 * automatically — students are never asked to type them.
 * Everyone in this list is {YEAR}, department {DEPARTMENT}.
 */

export const CSE_DEPARTMENT = {json.dumps(DEPARTMENT)};
export const CSE_YEAR = {json.dumps(YEAR)};

export interface CseStudent {{
  name: string;
  section: string;
}}

/** Registration number -> {{ name, section }}. {len(students)} students. */
export const CSE_STUDENTS: Record<string, CseStudent> = {{
{entries}
}};

/** The email of a student is <roll number>@andhrauniversity.edu.in. */
export const NOT_IN_CSE_LIST_MESSAGE =
  'This email is not in the second-year CSE list. AuPro is only for second-year CSE students right now. Contact the head administrator.';

/** Roll number from a college email address (its local part). */
export function getRollNoFromEmail(email: string | null | undefined): string {{
  if (!email) return '';
  return email.toLowerCase().trim().split('@')[0];
}}

/** Directory entry for a registration number, or null. */
export function lookupCseStudent(rollNo: string | null | undefined): CseStudent | null {{
  if (!rollNo) return null;
  return CSE_STUDENTS[String(rollNo).trim()] || null;
}}

/** Directory entry for a college email, with its roll number, or null. */
export function lookupCseStudentByEmail(
  email: string | null | undefined
): (CseStudent & {{ rollNo: string }}) | null {{
  const rollNo = getRollNoFromEmail(email);
  const student = lookupCseStudent(rollNo);
  if (!student) return null;
  return {{ rollNo, ...student }};
}}
"""
    OUT_TS.write_text(ts, encoding="utf-8")

    # --- cse-students.json (same data, for account-registry.ts) ---------
    OUT_JSON.write_text(
        json.dumps(
            {"department": DEPARTMENT, "year": YEAR, "students": students},
            ensure_ascii=False,
            indent=1,
            sort_keys=True,
        )
        + "\n",
        encoding="utf-8",
    )

    from collections import Counter

    sections = Counter(v["section"] for v in students.values())
    print(f"wrote {OUT_TS} ({len(students)} students)")
    print(f"wrote {OUT_JSON}")
    print("sections:", dict(sorted(sections.items())))


if __name__ == "__main__":
    main()
