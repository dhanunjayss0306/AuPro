// AuPro FAQ knowledge-base builder.
//
// Reads apps/web/app/faq-data.json (the researched college-office FAQ
// dataset: question, answer, documents, sources, verified flag,
// application flow) and generates apps/web/app/faq-data.ts — the
// QAEntry[] that the in-memory vector search (vector_search.ts)
// trains on.
//
// Only entries with "verified": true go into the app. UNVERIFIED
// entries stay in the JSON (marked) until someone verifies them —
// the app must never answer students with unverified procedures.
//
// Keywords are derived from the question + category so the vector
// search's keyword boost works; the dataset itself has no keywords.
//
// Run:  node scripts/build-faq-kb.mjs
// Re-run it after editing faq-data.json, then commit both files.

import * as fs from 'fs';
import * as path from 'path';
import { fileURLToPath } from 'url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const jsonPath = path.join(root, 'apps', 'web', 'app', 'lib', 'faq-data.json');
const tsPath = path.join(root, 'apps', 'web', 'app', 'lib', 'faq-data.ts');

const STOPWORDS = new Set(
  'a an the and or of to in for on with by is are was were be been do does did how what when where which who whom whose can could should would will shall may might i me my we our you your he she it its they them their this that these those there here from as at not no yes if then than so such into about after before between under over out up down off all any each few more most other some no nor only own same s get got apply application certificate certificates document documents required need needs'.split(
    ' ',
  ),
);

function keywordsFor(entry) {
  const words = new Set();
  // Question + category first, then distinctive words from the answer,
  // so an entry matches the purpose it serves (e.g. an income-certificate
  // answer that mentions scholarships matches "scholarship" queries).
  const text = `${entry.category} ${entry.question} ${entry.answer}`;
  for (const w of text
    .toLowerCase()
    .replace(/[^a-z0-9\s]/g, ' ')
    .split(/\s+/)
    .filter(Boolean)) {
    if (w.length >= 3 && !STOPWORDS.has(w)) words.add(w);
    if (words.size >= 14) break;
  }
  // Category words always included (fee, bonafide, scholarship...).
  for (const w of entry.category.toLowerCase().split(/[^a-z0-9]+/).filter(Boolean)) {
    if (w.length >= 3) words.add(w);
  }
  return [...words].slice(0, 14);
}

const raw = JSON.parse(fs.readFileSync(jsonPath, 'utf-8'));
const verified = raw.filter((e) => e.verified === true);
const skipped = raw.filter((e) => e.verified !== true);

const entries = verified.map((e) => ({
  id: e.id,
  category: e.category,
  question: e.question,
  answer: e.answer,
  keywords: keywordsFor(e),
}));

const header = `// Generated by scripts/build-faq-kb.mjs from faq-data.json — do not edit by hand.
// Only verified entries are included (${verified.length} of ${raw.length});
// ${skipped.length} UNVERIFIED ${skipped.length === 1 ? 'entry stays' : 'entries stay'} in faq-data.json until verified: ${skipped.map((e) => e.id).join(', ') || 'none'}.
// Re-run the script after editing faq-data.json.
import type { QAEntry } from './vector_search';

export const faqKnowledgeBase: QAEntry[] = `;
fs.writeFileSync(tsPath, header + JSON.stringify(entries, null, 2) + ';\n', 'utf-8');

console.log(`build-faq-kb: ${verified.length} verified entries -> ${path.relative(root, tsPath)}`);
if (skipped.length > 0) {
  console.log(`build-faq-kb: skipped UNVERIFIED: ${skipped.map((e) => e.id).join(', ')}`);
}
